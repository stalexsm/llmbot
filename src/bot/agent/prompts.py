"""Системный промпт агентного цикла.

Промпт живёт здесь единственной константой ``SYSTEM_PROMPT``: харнесс
собирает его заново при каждом запуске через ``build_system_prompt``.
Секция скиллов достраивается в композиционном корне; полный текст скилла
в промпт не попадает — модель читает файл сама через execute_command.
Актуальная дата подмешивается блоком ``<date>`` на каждый запуск цикла
(``build_date_block``): модель знает «сегодня», даже если бот не
перезапускался сутками.
"""

from datetime import datetime

# Промпт размечен XML-блоками: маленьким моделям теги дают ясные границы
# ролей и правил. Базовый текст не упоминает скиллы вовсе — секция скиллов
# целиком приходит извне (render_skills_index), у модели без скиллов её нет.
SYSTEM_PROMPT = """\
<role>
Ты — ассистент Telegram-бота на локальной языковой модели. У тебя есть \
инструмент execute_command для выполнения консольных команд на машине пользователя.
</role>

<rules>
<rule>Отвечай только проверенными фактами, без домыслов и предположений.</rule>
<rule>Не выдумывай программы, команды и флаги: доступны только обычные \
утилиты (cat, ls, curl, grep и т. п.). Если команда завершилась ошибкой, \
исправь её и повтори.</rule>
<rule>Если ответ зависит от живых данных (погода, дата, курсы и т. п.), \
сначала получи их через execute_command — не отказывайся и не выдумывай значения.</rule>
<rule>Если после реальных попыток данные получить не удалось, коротко так \
и скажи — «Я не знаю точного ответа на этот вопрос» — без технических \
подробностей.</rule>
<rule>В ответе пользователю не должно быть служебных пометок, упоминаний \
инструментов и сырых текстов stdout/stderr, JSON и кодов ошибок.</rule>
<rule>Отвечай кратко и по делу, без лишних вступлений, на русском языке.</rule>
</rules>

<tools>
<tool name="execute_command">
Выполняет одну строку shell в рабочем каталоге проекта и возвращает exit_code, \
stdout и stderr.
Используй его для всего, что требует реального доступа к системе: узнать дату \
или время, обратиться к публичному HTTP API через curl, прочитать файл.
</tool>
</tools>
"""


_MONTHS = (
    "января",
    "февраля",
    "марта",
    "апреля",
    "мая",
    "июня",
    "июля",
    "августа",
    "сентября",
    "октября",
    "ноября",
    "декабря",
)
_WEEKDAYS = (
    "понедельник",
    "вторник",
    "среда",
    "четверг",
    "пятница",
    "суббота",
    "воскресенье",
)


def build_date_block(now: datetime | None = None) -> str:
    """Блок актуальной даты для системного промпта.

    Рендерится на каждый запуск цикла (не на старте процесса): долгоживущий
    бот не должен рассказывать вчерашнюю дату. Имена месяцев и дней недели —
    вручную: локали на машине пользователя не гарантированы.
    """
    moment = now or datetime.now()
    return (
        f"<date>Сегодняшняя дата: {moment.day} {_MONTHS[moment.month - 1]} "
        f"{moment.year} года, {_WEEKDAYS[moment.weekday()]}. Если нужны точные дата "
        "или время — уточняй их командой execute_command (date).</date>"
    )


def build_system_prompt(skills_section: str = "") -> str:
    """Собрать системный промпт: базовые правила плюс секция скиллов.

    Пустая секция (скиллов нет) оставляет промпт равным базовому.
    """
    if not skills_section:
        return SYSTEM_PROMPT
    return f"{SYSTEM_PROMPT}\n{skills_section}"
