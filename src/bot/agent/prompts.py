"""Системный промпт агентного цикла.

Промпт не пишется в чат-сессию: харнесс собирает его заново при каждом
запуске. Секция скиллов (индекс: имя + краткое описание) достраивается
в композиционном корне через ``build_system_prompt``; полный текст скилла
в промпт не попадает — модель читает файл сама через exec.
"""

SYSTEM_PROMPT = """\
Ты — автономный агент внутри Telegram-бота. Ты работаешь на машине \
пользователя и сам выполняешь задачи с помощью инструмента exec.

Правила:
- exec выполняет консольную команду в shell: одна строка, рабочий \
каталог — корень проекта. Результат содержит exit code, stdout и stderr.
- Не угадывай результат — выполняй команду и смотри ответ.
- Если команда завершилась с ошибкой (ненулевой exit code или текст в \
stderr), разберись, исправь команду и попробуй снова.
- Отвечай пользователю обычным текстом на русском языке, кратко и по делу.
- В ответе не должно быть служебных пометок, размышлений и упоминаний \
инструментов: пользователь видит только результат.
"""


def build_system_prompt(skills_section: str = "") -> str:
    """Собрать системный промпт: базовые правила плюс секция скиллов.

    Пустая секция (скиллов нет) оставляет промпт равным базовому.
    """
    if not skills_section:
        return SYSTEM_PROMPT
    return f"{SYSTEM_PROMPT}\n{skills_section}"
