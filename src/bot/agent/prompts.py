"""Системный промпт агентного цикла.

Промпт живёт здесь единственной константой ``SYSTEM_PROMPT``: харнесс
собирает его заново при каждом запуске через ``build_system_prompt``.
Секция скиллов достраивается в композиционном корне; полный текст скилла
в промпт не попадает — модель читает файл сама через execute_command.
Актуальная дата подмешивается блоком ``<date>`` на каждый запуск цикла
(``build_date_block``): модель знает «сегодня», даже если бот не
перезапускался сутками.

Промпт сжат по данным аудита токенов (оптимизация 3, см.
``docs/token-optimization-report.md``): он уходит в каждый шаг каждого
запуска, поэтому формулировки ужаты до поведенчески значимого минимума,
дублирующая JSON-схему секция ``<tools>`` убрана. Гард от чрезмерного
сжатия — ``TestPromptBudget``: бюджет размера и семантические якоря.
"""

from datetime import datetime

# Промпт размечен XML-блоками: маленьким моделям теги дают ясные границы
# ролей и правил. Базовый текст не упоминает скиллы вовсе — секция скиллов
# целиком приходит извне (render_skills_index), у модели без скиллов её нет.
# Секция ``<tools>`` нарочно отсутствует: инструмент и так описан в JSON-схеме
# поля ``tools`` запроса, дублировать её словами — платить токенами за каждый
# шаг запуска (см. docs/token-optimization-report.md, оптимизация 3).
SYSTEM_PROMPT = """\
<role>
Ты — ассистент Telegram-бота на локальной языковой модели с инструментом \
execute_command (консоль на машине пользователя).
</role>

<rules>
<rule>Отвечай только проверенными фактами, без домыслов.</rule>
<rule>Не выдумывай команды и флаги: только реальные утилиты (cat, ls, curl, \
grep, …). Ошибку команды исправь и повтори.</rule>
<rule>Содержательный вопрос (в т.ч. по документам; даже если кажется, что \
о тебе) сначала проверяй через search_documents: запрос сформулируй сам, \
отвечай только найденным, указывая Источник — имя документа (и страницу, если \
есть). Без поиска не отвечай.</rule>
<rule>Если поиск не нашёл ответа, честно скажи, что его нет в документах — \
не выдумывай.</rule>
<rule>Живые данные (погода, дата, курсы) сначала получи через execute_command \
— не выдумывай значения.</rule>
<rule>Если данные получить не удалось, коротко ответь: «Я не знаю точного \
ответа на этот вопрос» — без технических подробностей.</rule>
<rule>В ответе пользователю не должно быть служебных пометок, упоминаний \
инструментов, сырого stdout/stderr, JSON и кодов ошибок.</rule>
<rule>Отвечай кратко и по делу, на русском языке.</rule>
</rules>
"""


_MONTHS = (
    "января",
    "февраля",
    "марта",
    "апреля",
    "мая",
    "июня",
    "июля",
    "августа",
    "сентября",
    "октября",
    "ноября",
    "декабря",
)
_WEEKDAYS = (
    "понедельник",
    "вторник",
    "среда",
    "четверг",
    "пятница",
    "суббота",
    "воскресенье",
)


def build_date_block(now: datetime | None = None) -> str:
    """Блок актуальной даты для системного промпта.

    Рендерится на каждый запуск цикла (не на старте процесса): долгоживущий
    бот не должен рассказывать вчерашнюю дату. Имена месяцев и дней недели —
    вручную: локали на машине пользователя не гарантированы.
    """
    moment = now or datetime.now()
    return (
        f"<date>Сегодня: {moment.day} {_MONTHS[moment.month - 1]} {moment.year}, "
        f"{_WEEKDAYS[moment.weekday()]}. Точные дату и время — командой "
        "execute_command (date).</date>"
    )


def build_system_prompt(skills_section: str = "") -> str:
    """Собрать системный промпт: базовые правила плюс секция скиллов.

    Пустая секция (скиллов нет) оставляет промпт равным базовому.
    """
    if not skills_section:
        return SYSTEM_PROMPT
    return f"{SYSTEM_PROMPT}\n{skills_section}"
