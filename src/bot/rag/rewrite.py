"""Порт переписывания Поискового запроса (conversation-aware поиск).

Уточняющий вопрос с местоимениями («А можно перенести их на следующий год?»)
сам по себе слабый Поисковый запрос: перед поиском один короткий вызов
чат-модели строит по вопросу и последним репликам диалога самостоятельную
формулировку. Rag-слой знает только этот порт; реализация поверх провайдера
инференса подключается в композиционном корне (``LlmQueryRewriter`` в
``bot.main``), поэтому границы слоёв не нарушаются.
"""

from typing import Protocol

from bot.domain.ids import RequestId


class QueryRewriter(Protocol):
    """Построить самостоятельный Поисковый запрос из вопроса и реплик диалога.

    ``question`` — запрос, подлежащий переписыванию (формулировка из вызова
    search_documents); ``recent_turns`` — отрендеренные реплики диалога,
    включая текущий вопрос пользователя. Реализация вправе бросить любое
    исключение: вызывающая сторона обязана при сбое упасть на сырой вопрос.
    """

    async def rewrite(
        self,
        request_id: RequestId,
        question: str,
        recent_turns: tuple[str, ...],
    ) -> str: ...
