"""Evaluation-датасет: вопросы с известными источниками и корпус документов.

Минимум задания — 5 вопросов с понятным источником; здесь их шесть, плюс
один вопрос «мимо корпуса» (``expected_source is None``) для калибровки
порога «не найдено»: релевантной информации в документах нет, и правильное
поведение поиска — пустой результат. Документы заведомо больше целевого
чанка (900 символов), чтобы поиск работал на реальном чанкинге, а не на
одно-чанковых файлах.
"""

from dataclasses import dataclass


@dataclass(frozen=True)
class EvaluationDocument:
    """Документ датасета: имя файла и содержимое (utf-8 текст)."""

    name: str
    content: str


@dataclass(frozen=True)
class EvaluationQuestion:
    """Вопрос датасета: формулировка и ожидаемый источник.

    ``expected_source is None`` — негативный вопрос: ответа в корпусе нет,
    попаданием считается отсутствие найденных чанков.
    """

    question: str
    expected_source: str | None


_VACATION_POLICY = """\
# Положение об отпусках

## Ежегодный оплачиваемый отпуск

Каждому сотруднику предоставляется ежегодный оплачиваемый отпуск
продолжительностью 28 календарных дней. Первый отпуск доступен
после шести месяцев непрерывной работы в компании.

Отпуск может быть разделён на части, если хотя бы одна из частей
не короче 14 календарных дней. Оставшиеся части оформляются
обычными заявлениями без ограничений на количество.

## Порядок согласования

Заявление на отпуск подаётся в отдел кадров не позднее чем за две
недели до первого дня отпуска. Согласование с руководителем отдела
обязательно: он подтверждает отсутствие критичных задач на даты
отпуска в течение трёх рабочих дней.

## Перенос и компенсация

Неиспользованная часть отпуска переносится на следующий рабочий
год. Замена отпуска денежной компенсацией допускается только для
его части сверх 28 календарных дней и только по письменному
согласованию сотрудника с работодателем.

## Отпуск без сохранения зарплаты

Отпуск без сохранения заработной платы предоставляется по семейным
обстоятельствам на срок до пяти календарных дней по заявлению
сотрудника; согласовывает его руководитель отдела.

## Дополнительный отпуск

Сотрудникам с ненормированным рабочим днём предоставляется
дополнительный оплачиваемый отпуск продолжительностью три
календарных дня; он присоединяется к основному отпуску.
"""

_OFFICE_HANDBOOK = """\
Справочник сотрудника: офис и быт

Рабочее время

Офис работает с 9:00 до 18:00 с понедельника по пятницу.
Гибкое начало дня позволяет прийти между 8:00 и 10:30,
окончание рабочего дня сдвигается соответственно. Перерыв
на обед — один час, его время сотрудник выбирает сам.

Пропуска и доступ

Пропуск выдаётся в первый рабочий день на ресепшене.
Потерянный пропуск восстанавливается за один рабочий день,
штраф за утерю не взимается. Гости допускаются только
по предварительной заявке на ресепшен.

Техника и рабочее место

Каждому сотруднику выдаётся ноутбук и монитор. Заявки
на дополнительное оборудование — через справочную систему;
срок поставки до пяти рабочих дней. Личное оборудование
подключать к корпоративной сети запрещено.

Парковка

На территории офиса есть бесплатная парковка. Место
закрепляется по заявке; при нехватке мест действует
живая очередь в справочной системе.

Столовая

Корпоративная столовая работает с 11:00 до 16:00.
Обед частично субсидируется компанией: фиксированный
комплексный обед обходится сотруднику в 150 рублей.
"""

_TRAVEL_POLICY = """\
Регулирование командировок

Оформление командировки

Командировка оформляется приказом не позднее чем за три
рабочих дня до даты выезда. Средний срок командировки —
не более десяти календарных дней; более длительные поездки
согласовываются с генеральным директором.

Суточные

Суточные при командировке по России выплачиваются в размере
700 рублей за каждый день, включая дни в пути. При зарубежных
командировках суточные составляют 2500 рублей в пересчёте
по курсу на дату выплаты.

Транспорт и проживание

Билеты покупает офис-менеджер по заявке сотрудника;
экономия от более дешёвого тарифа сотруднику не выплачивается.
Проживание оплачивается по счёту отеля, но не выше
5000 рублей за сутки в Москве и 3000 рублей в регионах.

Отчётность

Авансовый отчёт с чеками сдаётся в бухгалтерию в течение
трёх рабочих дней после возвращения. Неподтверждённые
расходы удерживаются из ближайшей выплаты сотрудника.

Отмена поездки

При отмене командировки неизрасходованный аванс возвращается
в кассу в день отмены; штрафы перевозчика при отмене по вине
компании оплачивает работодатель.
"""

_DOCUMENTS = (
    EvaluationDocument("vacation_policy.md", _VACATION_POLICY),
    EvaluationDocument("office_handbook.txt", _OFFICE_HANDBOOK),
    EvaluationDocument("travel_policy.md", _TRAVEL_POLICY),
)

_QUESTIONS = (
    EvaluationQuestion(
        "Сколько дней оплачиваемого отпуска положено сотруднику?", "vacation_policy.md"
    ),
    EvaluationQuestion("За сколько дней подаётся заявление на отпуск?", "vacation_policy.md"),
    EvaluationQuestion(
        "Какие суточные выплачиваются в командировке по России?", "travel_policy.md"
    ),
    EvaluationQuestion(
        "Сколько стоит комплексный обед в корпоративной столовой?", "office_handbook.txt"
    ),
    EvaluationQuestion("Как восстановить потерянный пропуск в офис?", "office_handbook.txt"),
    EvaluationQuestion("Какие условия аренды переговорных в коворкинге?", None),
)


def evaluation_documents() -> tuple[EvaluationDocument, ...]:
    """Корпус документов датасета: три документа по разным темам."""
    return _DOCUMENTS


def evaluation_questions() -> tuple[EvaluationQuestion, ...]:
    """Вопросы датасета: пять с источником и один негативный."""
    return _QUESTIONS
